#!/usr/bin/env python3
"""
Generate a per-language font description from the game's own strings, so the font holds only the characters it draws.

Why: a font that carries a whole CJK block is megabytes. The game only ever draws the characters in its own strings, so for
each language given this script reads Core/Strings.<lang>.resx and writes Content/Fonts/<lang>Large|Medium|Small.spritefont
with a CharacterRegion for each run of characters actually used (plus printable ASCII, which every screen needs for names and numbers).
The glyphs come from the Unifont file already in Content/Fonts. The same idea as Royal Flush Rush's generate-cjk-fonts.py,
without the font-file subsetting, because Unifont is already in the repository.

Run it again whenever Core/Strings.<lang>.resx changes (new or reworded strings), then rebuild the content:

    python3 scripts/generate-cjk-fonts.py ko
    python3 scripts/generate-cjk-fonts.py ko --check     # list any character the Unifont file has no glyph for

The Content.mgcb entries for these fonts use the plain FontDescriptionProcessor and the output name retro<Size>.<lang>,
which is where LoadLocalized looks for the language's font.
"""
import argparse
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "Content" / "Fonts"

# role -> point size (the same as retroLarge, retroMedium and retroSmall)
SIZES = {"Large": 24, "Medium": 20, "Small": 16}

# always drawn: printable ASCII (names, numbers, punctuation), plus a few typographic marks. A character outside the set (an accented
# letter in a player's name) is drawn as a question mark, which the font description names as its default.
BASE = set(range(0x20, 0x7F)) | {0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2013, 0x2014}


def resx_chars(lang):
    path = ROOT / "Core" / f"Strings.{lang}.resx"
    if not path.exists():
        sys.exit(f"Missing {path}")
    chars = set()
    for data in ET.parse(path).getroot().iter("data"):
        value = data.find("value")
        if value is not None and value.text:
            chars.update(ord(c) for c in value.text if ord(c) >= 0x20)
    return chars


def ranges(codepoints):
    out, start, prev = [], None, None
    for cp in sorted(codepoints):
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            out.append((start, prev))
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def spritefont_xml(size, codepoints, lang):
    regions = "".join(
        f"      <CharacterRegion>\n        <Start>&#{a};</Start>\n        <End>&#{b};</End>\n      </CharacterRegion>\n"
        for a, b in ranges(codepoints)
    )
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by scripts/generate-cjk-fonts.py - do not edit by hand.
  The '{lang}' font: Unifont, only the characters in Core/Strings.{lang}.resx plus printable ASCII.
-->
<XnaContent xmlns:Graphics="Microsoft.Xna.Framework.Content.Pipeline.Graphics">
  <Asset Type="Graphics:FontDescription">
    <FontName>unifont-16.0.04</FontName>
    <Size>{size}</Size>
    <Spacing>3</Spacing>
    <UseKerning>false</UseKerning>
    <Style>Regular</Style>
    <DefaultCharacter>?</DefaultCharacter>
    <CharacterRegions>
{regions}    </CharacterRegions>
  </Asset>
</XnaContent>
"""


def font_covers(codepoints):
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        sys.exit("--check needs fontTools:  pip install fonttools")
    cmap = TTFont(str(FONTS / "unifont-16.0.04.otf")).getBestCmap()
    return [cp for cp in codepoints if cp not in cmap]


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("langs", nargs="+", help="language codes whose Core/Strings.<lang>.resx to read, such as ko")
    parser.add_argument("--check", action="store_true", help="only report characters the Unifont file cannot draw")
    args = parser.parse_args()

    for lang in args.langs:
        codepoints = BASE | resx_chars(lang)
        if args.check:
            missing = font_covers(codepoints)
            print(f"{lang}: {len(codepoints)} characters, {len(missing)} without a glyph" + ("".join(" " + chr(c) for c in missing)))
            continue
        for role, size in SIZES.items():
            path = FONTS / f"{lang}{role}.spritefont"
            path.write_text(spritefont_xml(size, codepoints, lang), encoding="utf-8")
        print(f"{lang}: wrote 3 fonts with {len(codepoints)} characters")


if __name__ == "__main__":
    main()
